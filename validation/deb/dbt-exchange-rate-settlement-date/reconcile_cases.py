"""Recompute case proofs from immutable public-input/output artifacts."""
import argparse
from collections import Counter
from datetime import datetime
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / 'src'))
from dbt_bench.io import evidence_ref, file_hash, read_json, tree_hash, write_json
from independent import encoded, derive, compare


def reconcile(batch):
    manifest = read_json(batch / 'manifest.json')
    expected = {p['task_label']: p for p in manifest['planned']}
    seen, trials = set(), []
    for path in sorted((batch / 'jobs').glob('*/*/result.json')):
        result = read_json(path)
        label = Path(result['config']['task']['path']).name
        if label not in expected or label in seen:
            raise ValueError('Unknown or duplicate case trial: ' + label)
        seen.add(label)
        declared = manifest['tasks'][label]
        assert tree_hash(batch / 'tasks' / label) == declared['validation_copy_hash']
        case = read_json(ROOT / declared['case']['path'])
        assert file_hash(ROOT / declared['case']['path']) == declared['case']['sha256']
        proof_path = path.parent / 'agent/case-proof.json'
        proof = read_json(proof_path) if proof_path.exists() else None
        snapshots, timestamp_checks = {}, {}
        valid = False
        if proof:
            assert proof['case'] == expected[label]['case_mode']
            assert proof['tested_checker_invoked_to_define_validity'] is False
            inputs_path = path.parent / 'agent/fx-inputs.json'
            assert file_hash(inputs_path) == case['pristine_inputs_sha256']
            desired, grain = derive(read_json(inputs_path))
            assert grain == proof['facts']['grain_review']
            for when in ['before', 'after']:
                snapshot_path = path.parent / f'agent/fx-{when}/snapshot.json'
                record = next(r for r in proof['submission_artifacts'] if r['path'].endswith(f'/fx-{when}/snapshot.json'))
                assert file_hash(snapshot_path) == record['sha256']
                snapshot = read_json(snapshot_path)
                for source in snapshot['files']:
                    relative = source['path'].split(f'/fx-{when}/', 1)[1]
                    assert file_hash(snapshot_path.parent / relative) == source['sha256']
                comparison = compare(desired, snapshot, case['preserved_columns'])
                assert comparison == proof['facts']['baseline_comparison' if when == 'before' else 'comparison']
                if when == 'before':
                    assert comparison['equal']
                snapshots[when] = evidence_ref(snapshot_path, ROOT)
                # The original model defines current_timestamp metadata. Record
                # and bound it to its actual build, rather than silently delete it.
                run = read_json(snapshot_path.parent / 'target/run_results.json')
                timings = [t for r in run['results'] for t in r['timing'] if t['name'] == 'execute']
                parse = lambda t: datetime.fromisoformat(t.replace('Z', '+00:00'))
                start = min(parse(t['started_at']) for t in timings)
                end = max(parse(t['completed_at']) for t in timings)
                values = snapshot['dbt_updated_at_values']
                timestamp_checks[when] = {'values': values, 'build_started': start.isoformat(),
                                         'build_finished': end.isoformat(),
                                         'within_build': all(v != 'None' and start <= parse(v) <= end for v in values),
                                         'scope': 'Table metadata must be generated by its actual build; views evaluate current_timestamp when read.'}
                if snapshot['table_type'] == 'BASE TABLE':
                    assert timestamp_checks[when]['within_build']
            valid = result.get('exception_info') is None
        rewards = (result.get('verifier_result') or {}).get('rewards')
        log_path = path.parent / 'verifier/test-stdout.txt'
        log = log_path.read_text() if log_path.exists() else ''
        outcome = 'unresolved_execution'
        if valid and rewards == {'reward': 1.0}:
            outcome = 'missed_wrong' if case['kind'] == 'negative' else 'accepted_scoped_positive'
        elif valid and rewards == {'reward': 0.0}:
            # Do not treat a fixture setup/build/SQL error as semantic detection.
            if 'ERROR at setup' not in log and 'ERROR collecting' not in log and 'E   duckdb.' not in log and 'AssertionError:' in log:
                outcome = 'detected_wrong' if case['kind'] == 'negative' else 'rejected_scoped_positive'
        trials.append({**expected[label], 'trial_id': result['id'], 'raw_directory': str(path.parent.relative_to(ROOT)),
                       'kind': case['kind'], 'case_outcome': outcome, 'native_rewards': rewards,
                       'exception_info': result.get('exception_info'),
                       'proof_validity': proof['validity'] if proof else None,
                       'independent_proof': evidence_ref(proof_path, ROOT) if proof else None,
                       'snapshots': snapshots, 'metadata_timestamp_checks': timestamp_checks,
                       'result': evidence_ref(path, ROOT), 'native_log': evidence_ref(log_path, ROOT) if log_path.exists() else None,
                       'scope': 'Scoped proof only; reference grain alignment and other protocol items remain unresolved.'})
    report = {'schema_version': 1, 'planned_trials': len(expected), 'observed_trials': len(trials),
              'missing': sorted(expected.keys() - seen), 'coverage_complete': set(expected) == seen,
              'outcomes': dict(Counter(t['case_outcome'] for t in trials)), 'trials': trials,
              'scope': 'All original results retained. Positive cases use native reference grain interpretation, not full task certification.'}
    output = batch / 'reconciliation.json'
    if output.exists():
        raise FileExistsError(output)
    write_json(output, report)
    print({k: report[k] for k in ['planned_trials', 'observed_trials', 'missing', 'outcomes']})
    return 0 if report['coverage_complete'] else 1


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--batch', type=Path, required=True)
    args = parser.parse_args()
    raise SystemExit(reconcile(args.batch.resolve()))
