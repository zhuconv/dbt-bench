def run(out):
    out.mkdir(parents=True, exist_ok=False)
    ref = lambda p: evidence_ref(p, ROOT)
    trial = ROOT / 'jobs/spider2-qwen-gh-dev-1124050-attempt-2/spider2__workday002__YWRFyUb'
    session = trial / 'agent/qwen-sessions/-workspace/chats/69fbe8f0-9a2b-4d62-825a-623178d591b9.jsonl'
    assert file_hash(session) == 'd8d55b4feea60c82bb3ae4344169ea2d4287f79d0752facc007ee16ef575cdce'
    inventory = read_json(ROOT / 'validation/evidence/spider-real-smoke-v1/trial-artifacts.json')
    original = {r['path']: r for r in inventory}
    assert evidence_ok(original[session.relative_to(ROOT).as_posix()], ROOT)
    request = read_json(ROOT / 'artifacts/validation/workday-collected-audit-v2/inputs/model-replay.json')
    capture, snapshot = load_capture(ROOT, request['before'], 'before-native')
    for name in ['logs/dbt.log', 'target/manifest.json', 'target/run_results.json']:
        original_path = trial / 'artifacts/submission/workspace' / name
        assert evidence_ok(original[original_path.relative_to(ROOT).as_posix()], ROOT)
        assert file_hash(capture / name) == file_hash(original_path)
    events = [json.loads(line) for line in session.read_text().splitlines()]
    parsed = qwen_calls(events, AUXILIARY)
    calls = parsed['calls']
    by_id = {c['id']: c for c in calls}
    assert len(calls) == 65 and all(c['response'] and c['telemetry'] for c in calls)
    history = invocations((capture / 'logs/dbt.log').read_text())
    assert len(history) == 10
    manifest = read_json(capture / 'target/manifest.json')
    assert manifest['metadata']['dbt_version'] == '1.10.22'
    required_ids = read_json(HERE.parent / 'audit_v2/input-policy.json')['required_model_ids']
    assert len(required_ids) == 50
    expected = {
        DEPS: '203e970c-842d-474a-a2b2-8dbd73eada49',
        FULL: 'b3634868-2628-42c9-905f-d6910820fb2b',
        PARTIAL: 'c80c5cb5-e0fc-4796-a4f0-0b8ad9f0861b',
        TEST_SELECTED: '9dda6a92-4620-45c0-9a79-364d1345d114',
        TEST_ALL: '33c209b0-2814-4e0f-ad9a-e0b930665352',
    }
    bound = [bind_invocation(by_id[call_id], next(h for h in history if h['invocation_id'] == iid), manifest)
             for call_id, iid in expected.items()]
    full = next(r for r in bound if r['call_id'] == FULL)
    assert by_id[DEPS]['response']['line'] < by_id[FULL]['line']
    package_changes = [c for c in calls if c['name'] in {'write_file', 'edit'}
                       and c['args'].get('file_path') == '/workspace/packages.yml']
    assert len(package_changes) == 3 and all(c['response']['line'] < by_id[DEPS]['line'] for c in package_changes)
    assert (capture / 'project/packages.yml').exists()
    later = [c for c in calls if c['line'] > by_id[FULL]['response']['line']]
    effects = {key: {'kind': 'read_only_query'} for key in READ_ONLY}
    effects['call_9d6c79c604f94d36b089a387'] = {'kind': 'outside_project_cli_install',
        'reason': 'Observed successful duckdb-cli 2.0.0 wheel installation outside project; exact workspace replay previously succeeded without restoring this CLI.'}
    effects[SOURCE_WRITE] = {'kind': 'source_write', 'node_id': TARGET}
    effects[PARTIAL] = {'kind': 'dbt_run'}
    effects[TEST_SELECTED] = effects[TEST_ALL] = {'kind': 'dbt_test'}
    effects = {key: {**effect, 'args_sha256': by_id[key]['args_sha256']} for key, effect in effects.items()}
    assessment = assess_post_build(required_ids, full, later, effects, bound, manifest)
    assert assessment['status'] == 'pass', assessment
    source = capture / 'project' / manifest['nodes'][TARGET]['original_file_path']
    assert source.read_text().strip() == by_id[SOURCE_WRITE]['args']['content'].strip() == manifest['nodes'][TARGET]['raw_code'].strip()
    assert file_hash(source) == snapshot['project_files'][manifest['nodes'][TARGET]['original_file_path']]['sha256']
    run_results = read_json(capture / 'target/run_results.json')
    assert run_results['args']['which'] == 'test' and len(run_results['results']) == 67
    assert run_results['metadata']['invocation_id'] == expected[TEST_ALL]
    refs = [ROOT / 'tasks/spider2__workday002/instruction.md',
            ROOT / 'artifacts/validation/workday-semantics-source-v1/upstream/models/docs.md',
            ROOT / 'artifacts/validation/workday-semantics-source-v1/upstream/models/workday.yml',
            ROOT / 'artifacts/validation/workday-semantics-source-v1/upstream/models/workday__job_overview.sql']
    facts = dict(schema_version=1, task_key='spider2__workday002',
        decision='underspecified_keep_unknown', input_sources=[ref(p) for p in refs],
        docs_lines=[360, 366, 372, 382], upstream_sql_lines=[56, 57, 58, 59],
        task_rule='Aggregate job profile, family and family-group details; no explicit empty aggregate representation rule.',
        docs_rule='The four aggregate descriptions say String array, without an empty-member/empty-set serialization policy.',
        reference_rule='Distinct string aggregation with comma-space delimiter; no COALESCE for an empty aggregate.',
        known_accepted_representations=['SQL NULL for no non-NULL members', 'empty VARCHAR[] for no members'],
        unresolved='Empty VARCHAR is also the serialization of one actual empty-string member. The fixed specification supplies no rule to distinguish it from an empty set.',
        consequence='Neither accepting nor rejecting empty VARCHAR is certified as native task semantics. Keep those model cells unknown; a stricter or permissive explicit variant would need a new task/checker policy version.',
        checker_changed=False, native_reward_changed=False)
    write_json(out / 'empty-representation-review.json', facts)
    write_json(out / 'dbt-invocations.json', history)
    write_json(out / 'reviewed-tool-effects.json', effects)
    write_json(out / 'bound-invocations.json', bound)
    write_json(out / 'post-build-tools.json', [{k:c[k] for k in ['id','name','args','line','args_sha256']} for c in later])
    write_json(out / 'auxiliary-telemetry.json', parsed['auxiliary_telemetry'])
    summary = dict(schema_version=1, task_key='spider2__workday002', certified=False,
        workflow=assessment, model_audit_reward=None, native_reward_modified=False,
        source_session=ref(session), snapshot=request['before'],
        original_trial=ref(trial / 'result.json'), required_ids=ref(HERE.parent / 'audit_v2/input-policy.json'),
        invocations=ref(out / 'dbt-invocations.json'), bound_invocations=ref(out / 'bound-invocations.json'),
        reviewed_effects=ref(out / 'reviewed-tool-effects.json'), post_build_tools=ref(out / 'post-build-tools.json'),
        source=ref(source), final_manifest=ref(capture / 'target/manifest.json'),
        final_run_results=ref(capture / 'target/run_results.json'), final_artifact_kind='test',
        real_successful_full_runs=1, later_target_only_runs=1, later_test_runs=2,
        earlier_failed_dbt_invocations=sum(not r['succeeded'] for r in history),
        main_tool_calls=65, reviewed_post_build_calls=len(later), empty_policy=ref(out / 'empty-representation-review.json'),
        auxiliary_tool_calls=9, auxiliary_telemetry=ref(out / 'auxiliary-telemetry.json'),
        missing_auxiliary_result_body='call_5c033f6259704314a70ccf9d',
        observer=ref(HERE / 'observe.py'), reviewer=ref(Path(__file__)),
        new_benchmark_trials=0, new_model_trials=0, new_submission_replays=0,
        remaining=['Production capture must retain per-invocation artifacts before later commands overwrite them.',
                   'Alternate model identities and non-leaf edits need an explicit dependency-closure review.',
                   'Overall data audit stays unknown for empty VARCHAR; terminal memory tool-result body remains missing.'],
        scope='Scoped actual main-session workflow review, independently bound to native stdout and retained dbt log. It does not fabricate historical run_results, modify native scores, certify semantic correctness or repair missing model context.')
    write_json(out / 'summary.json', summary)
    print({k:summary[k] for k in ['real_successful_full_runs','later_target_only_runs','later_test_runs','earlier_failed_dbt_invocations','reviewed_post_build_calls','model_audit_reward']})


if __name__ == '__main__':
    import argparse
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--output-dir', type=Path, required=True)
    run(parser.parse_args().output_dir.resolve())
